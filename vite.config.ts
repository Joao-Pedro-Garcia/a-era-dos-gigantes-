import { createHash } from 'node:crypto';
import { readFileSync, readdirSync } from 'node:fs';
import { defineConfig, type Plugin } from 'vite';

/**
 * Generates `sw.js` at build time with the exact list of files produced by
 * the build (hashed JS/CSS, index.html, manifest, icon). The service worker
 * pre-caches all of them atomically on install, so the game can start with
 * no network once the first visit completes.
 */
function offlinePrecache(): Plugin {
  return {
    name: 'edg-offline-precache',
    apply: 'build',
    generateBundle(_opts, bundle) {
      const files = new Set<string>(['./', 'index.html']);
      for (const f of Object.keys(bundle)) files.add(f);
      // Every file under public/ (recursively), e.g. models/manifest.json and any .glb listed there.
      // Their contents count for the version too: a model replaced under the same name
      // must reach players (it used to stay cached forever).
      const hash = createHash('sha256');
      const walk = (dir: string, prefix: string) => {
        for (const e of readdirSync(dir, { withFileTypes: true })) {
          if (e.isDirectory()) walk(`${dir}/${e.name}`, `${prefix}${e.name}/`);
          else {
            files.add(`${prefix}${e.name}`);
            hash.update(readFileSync(`${dir}/${e.name}`));
          }
        }
      };
      walk('public', '');
      const list = [...files].sort();
      const version = hash.update(list.join('|')).update(Object.values(bundle).map((b) => ('code' in b ? b.code : String(b.source ?? ''))).join('')).digest('hex').slice(0, 12);
      const source = `// Generated by vite.config.ts — do not edit.
const VERSION = 'edg-${version}';
const PRECACHE = ${JSON.stringify(list)};
self.addEventListener('install', (e) => {
  // addAll is all-or-nothing: a missing or failed file aborts the install, so a
  // half-cached (inconsistent) version can never become active.
  e.waitUntil(caches.open(VERSION).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== VERSION).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  if (req.mode === 'navigate') {
    // Network first for the page (to pick up updates), cached copy when offline.
    e.respondWith(fetch(req).catch(() => caches.match('index.html', { cacheName: VERSION }).then((r) => r || caches.match('./'))));
    return;
  }
  // Files with fixed names (models, their manifest): network first, so an updated
  // model is seen on the very next visit; the cached copy only when offline.
  if (!new URL(req.url).pathname.includes('/assets/')) {
    e.respondWith(fetch(req).then((res) => {
      if (res.ok) { const copy = res.clone(); caches.open(VERSION).then((c) => c.put(req, copy)); }
      return res;
    }).catch(() => caches.match(req, { cacheName: VERSION })));
    return;
  }
  // Hashed assets never change: cache first.
  e.respondWith(caches.match(req, { cacheName: VERSION }).then((hit) => hit || fetch(req).then((res) => {
    if (res.ok) { const copy = res.clone(); caches.open(VERSION).then((c) => c.put(req, copy)); }
    return res;
  })));
});
self.addEventListener('message', (e) => {
  if (e.data !== 'status') return;
  caches.open(VERSION).then(async (c) => {
    let n = 0;
    for (const f of PRECACHE) if (await c.match(f)) n++;
    e.source && e.source.postMessage({ type: 'offline-status', cached: n, total: PRECACHE.length, version: VERSION });
  });
});
`;
      this.emitFile({ type: 'asset', fileName: 'sw.js', source });
    },
  };
}

export default defineConfig({
  base: './',
  plugins: [offlinePrecache()],
  worker: { format: 'es' },
  build: {
    target: 'es2022',
    chunkSizeWarningLimit: 1500,
  },
  server: { host: true },
});
